/**
 * Returns a consistent, deterministic daily verse for a given calendar date string (YYYY-MM-DD).
 * Works cyclically through the curated schedule so every day gets a designated verse.
 */
export function getDeterministicDailyVerse(dateStr: string): DailyVerseRecord {
  // First check if an exact date match exists
  const exact = CURATED_DAILY_VERSES.find(v => v.date === dateStr);
  if (exact) return exact;

  // Otherwise calculate a deterministic hash index based on the date string
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    hash = (hash << 5) - hash + dateStr.charCodeAt(i);
    hash |= 0;
  }
  const index = Math.abs(hash) % CURATED_DAILY_VERSES.length;
  const template = CURATED_DAILY_VERSES[index];

  return {
    ...template,
    id: `verse-${dateStr}`,
    date: dateStr,
  };
}
